const DICTS: Record<Locale, Record<string, string>> = { 'zh-CN': ZH, en: EN }
const KEY = 'midee.locale'
const listeners = new Set<() => void>()

function detect(): Locale {
  try {
    const saved = localStorage.getItem(KEY)
    if (saved === 'zh-CN' || saved === 'en') return saved
  } catch {
    /* 隐私模式下 localStorage 不可用，忽略 */
  }
  return navigator.language?.toLowerCase().startsWith('zh') ? 'zh-CN' : 'en'
}

let current: Locale = detect()

export function getLocale(): Locale {
  return current
}

export function setLocale(next: Locale): void {
  current = next
  try {
    localStorage.setItem(KEY, next)
  } catch {
    /* noop */
  }
  document.documentElement.lang = next
  applyI18n(document)
  for (const fn of listeners) fn()
}

export function onLocaleChange(fn: () => void): () => void {
  listeners.add(fn)
  return () => {
    listeners.delete(fn)
  }
}

/** 取文案；缺 key 时回退英文，再回退 key 本身。支持 {n} 形式的插值。 */
export function t(key: string, params?: Record<string, string | number>): string {
  const raw = DICTS[current][key] ?? DICTS.en[key] ?? key
  if (!params) return raw
  return raw.replace(/\{(\w+)\}/g, (m, k: string) => {
    const v = params[k]
    return v === undefined ? m : String(v)
  })
}

/**
 * 扫描 [data-i18n]（文本）、[data-i18n-title]（title）、[data-i18n-aria]（aria-label）
 * 并写入当前语言的文案。页面 HTML 里写 data-i18n 即可自动双语。
 */
export function applyI18n(root: ParentNode): void {
  for (const el of root.querySelectorAll<HTMLElement>('[data-i18n-html]')) {
    const key = el.dataset.i18nHtml
    // 键均为开发侧静态字典，innerHTML 只受我们自己的文案控制
    if (key) el.innerHTML = t(key)
  }
  for (const el of root.querySelectorAll<HTMLElement>('[data-i18n]')) {
    const key = el.dataset.i18n
    if (key) el.textContent = t(key)
  }
  for (const el of root.querySelectorAll<HTMLElement>('[data-i18n-title]')) {
    const key = el.dataset.i18nTitle
    if (key) el.title = t(key)
  }
  for (const el of root.querySelectorAll<HTMLElement>('[data-i18n-aria]')) {
    const key = el.dataset.i18nAria
    if (key) el.setAttribute('aria-label', t(key))
  }
}
