/** 分类路径 → 中文（各段查表；未收录段保留英文） */
export function catPathZh(path: string): string {
  if (!path) return "";
  return path
    .split("/")
    .map((s) => CAT_SEG_ZH[s] ?? s)
    .join(" / ");
}

/** 分类路径最后一段的中文（资源列表里做短名用） */
export function catLeafZh(path: string): string {
  const parts = path.split("/");
  const leaf = parts[parts.length - 1] ?? "";
  return CAT_SEG_ZH[leaf] ?? leaf;
}

/** 资源英文名 → 中文（逐词翻译，数字编号保留；未收录词原样保留） */
export function texNameZh(name: string): string {
  const parts = name.match(/[A-Za-z]+|\d+/g) ?? [];
  let out = "";
  for (const p of parts) {
    if (/^\d+$/.test(p)) {
      out = `${out.trimEnd()} ${p}`;
      continue;
    }
    const key = p.toLowerCase();
    const zh = WORD_ZH[key];
    if (zh) out += zh;
    else out += `${out ? " " : ""}${p}`;
  }
  return out.trim() || name;
}
